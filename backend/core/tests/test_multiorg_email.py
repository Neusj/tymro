"""Invariantes del rediseño: email único por org + subdominio + username oculto.

- Email puede repetirse entre orgs, pero no dentro de la misma org.
- El subdominio del Host resuelve la organización (404 si no existe).
- El login es por email, acotado al subdominio.
- /api/users/ ya no expone username; la org se crea con subdominio (validado).
"""
import pytest
from django.contrib.auth import get_user_model
from django.db import IntegrityError

User = get_user_model()

pytestmark = pytest.mark.django_db

PASSWORD = 'Passw0rd2026'


# --- Email único por organización -------------------------------------------

def test_same_email_in_two_orgs_is_allowed(make_organization, make_user):
    org_a = make_organization('A')
    org_b = make_organization('B')
    u_a = make_user('juan_a', organization=org_a, role='student', email='juan@demo.local')
    u_b = make_user('juan_b', organization=org_b, role='teacher', email='juan@demo.local')
    assert u_a.email == u_b.email
    assert u_a.organization_id != u_b.organization_id


def test_dup_email_same_org_violates_db_constraint(make_organization, make_user):
    org_a = make_organization('A')
    make_user('first', organization=org_a, email='dup@demo.local')
    with pytest.raises(IntegrityError):
        # Case-insensitive: 'DUP@..' colisiona con 'dup@..' dentro de la misma org.
        make_user('second', organization=org_a, email='DUP@demo.local')


def test_api_create_dup_email_same_org_returns_400(api_client, make_organization, make_user):
    org_a = make_organization('A')
    admin = make_user('admin_a', organization=org_a, role='gym_admin', email='admin@a.local')
    make_user('taken', organization=org_a, role='student', email='taken@a.local')
    api_client.force_authenticate(admin)

    resp = api_client.post(
        '/api/users/',
        {'email': 'taken@a.local', 'role': 'student', 'password': PASSWORD, 'organization': org_a.id},
        format='json',
    )
    assert resp.status_code == 400
    assert 'email' in resp.data


# --- Username oculto ---------------------------------------------------------

def test_users_api_does_not_expose_username(api_client, make_organization, make_user):
    org_a = make_organization('A')
    admin = make_user('admin_a', organization=org_a, role='gym_admin', email='admin@a.local')
    api_client.force_authenticate(admin)

    resp = api_client.get(f'/api/users/{admin.id}/')
    assert resp.status_code == 200
    assert 'username' not in resp.data
    assert resp.data['email'] == 'admin@a.local'


def test_api_created_user_gets_opaque_autogenerated_username(api_client, make_organization, make_user):
    org_a = make_organization('A')
    admin = make_user('admin_a', organization=org_a, role='gym_admin', email='admin@a.local')
    api_client.force_authenticate(admin)

    resp = api_client.post(
        '/api/users/',
        {'email': 'nuevo@a.local', 'role': 'student', 'password': PASSWORD, 'organization': org_a.id},
        format='json',
    )
    assert resp.status_code == 201, resp.data
    created = User.objects.get(email__iexact='nuevo@a.local')
    # username auto-generado, opaco (uuid hex de 32), nunca igual al email.
    assert created.username and created.username != created.email
    assert len(created.username) == 32


